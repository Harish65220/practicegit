# 1. Hello World (Basic Output)
print("Hello, World!")

# 2. Variables and Basic Arithmetic
num1 = 10
num2 = 5
result = num1 + num2
print(f"The sum of {num1} and {num2} is: {result}")

# 3. Conditional Statements (If/Else)
score = 75
if score >= 70:
    print("Passing score.")
else:
    print("Below passing score.")

# 4. Loops (For Loop)
print("Counting from 1 to 5:")
for i in range(1, 6):
    print(i)

# 5. Functions
def greet(name):
    return f"Hello, {name}!"

welcome_message = greet("Alice")
print(welcome_message)
